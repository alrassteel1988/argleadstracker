const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const read = file => fs.readFileSync(path.join(__dirname, "..", file), "utf8");
const css = read("crm-dialogs.css");
assert.match(css, /body dialog\s*\{[^}]*var\(--crm-border\)[^}]*var\(--crm-surface\)/s);
assert.match(css, /\.ai-assistant-header\)\s*\{[^}]*background:\s*var\(--crm-navy\)/s);
assert.match(css, /\.crm-title-accent\s*\{[^}]*var\(--crm-amber\)/s);
assert.match(css, /\[aria-invalid="true"\]\s*\{[^}]*var\(--crm-health-red\)/s);
assert.match(css, /:disabled\s*\{[^}]*opacity:\s*1\s*!important/s);
assert.match(css, /@media \(max-width: 720px\)[\s\S]*min-height:\s*44px[^}]*font-size:\s*16px/s);
assert.doesNotMatch(css, /(?:linear|radial)-gradient|backdrop-filter:\s*blur|filter:\s*blur|rgba\(/);
const html = read("index.html");
assert.ok(html.indexOf('/crm-dialogs.css?v=') > html.indexOf('/crm-reports.css?v='));
const config = JSON.parse(read("vercel.json"));
assert.ok(config.builds.some(item => item.src === "crm-dialogs.css"));
assert.ok(config.routes.some(item => item.src === "/crm-dialogs.css" && item.dest === "/crm-dialogs.css"));
assert.ok(read("server.js").includes('["/crm-dialogs.css", "crm-dialogs.css"]'));
assert.ok(read("sw.js").includes('"/crm-dialogs.css"'));
const client = read("client.js");
const declaration = name => client.match(new RegExp(`function ${name}\\([^]*?\\n}`, "m"))[0];
const context = { kanbanStageForLead: ({stage}) => String(stage).toUpperCase(), KANBAN_STAGE_BY_KEY: { LOST: {label:"Lost"}, NEW: {label:"New"} } };
vm.createContext(context);
vm.runInContext(`${client.match(/const STAGE_DISPLAY_LABELS = Object\.freeze\([^]*?\);/)[0]} ${declaration("stageDisplayLabel")}; result = [stageDisplayLabel("LOST"), stageDisplayLabel("NEW")];`, context);
assert.deepEqual(Array.from(context.result), ["Blocked", "Prospect"]);
assert.match(client, /CLOSED_STAGE_KEYS = new Set\(\["WON", "DORMANT", "LOST"\]\)/);
assert.match(client, /label: "Blocked", value: pipelineCounts\.LOST, type: "salesmanStageLost"/);
assert.match(client, /STAGE_DISPLAY_LABELS\[normalizeStageKey\(option\.value, ""\)\]/);
console.log("PASS shared dialog presentation and display-only Blocked label contracts");
