const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const read = file => fs.readFileSync(path.join(__dirname, "..", file), "utf8");
const css = read("crm-reports.css");
assert.match(css, /\.tasks-header\s*\{[^}]*background:\s*var\(--crm-surface\)/s);
assert.match(css, /\.tasks-section-head h3\s*\{[^}]*color:\s*var\(--crm-navy\)[^}]*20px/s);
assert.match(css, /\.tasks-layout\s*\{[^}]*minmax\(0, 1\.7fr\) minmax\(290px, 0\.8fr\)/s);
assert.match(css, /:is\(\.tasks-primary, \.tasks-sidebar\)\s*\{[^}]*max-height:\s*calc\(100dvh - 260px\)[^}]*overflow-y:\s*auto/s);
assert.match(css, /field--required-empty\s*\{[^}]*var\(--crm-health-amber\)[^}]*var\(--crm-health-amber-soft\)/s);
assert.match(css, /field--filled\s*\{[^}]*var\(--crm-health-green\)[^}]*var\(--crm-health-green-soft\)/s);
assert.match(css, /#tasksWeekLabel\s*\{[^}]*color:\s*var\(--crm-navy\)[^}]*-webkit-text-fill-color:\s*currentColor/s);
assert.match(css, /\.tasks-actions-card\s*\{[^}]*padding-bottom:\s*76px\s*!important/s);
assert.match(css, /@media \(max-width: 1024px\)[\s\S]*\.tasks-sidebar\s*\{\s*order:\s*0/s);
assert.match(css, /@media \(max-width: 720px\)[\s\S]*min-height:\s*44px[^}]*font-size:\s*16px/s);
assert.doesNotMatch(css, /rgba\(|blur\(|opacity:\s*0\.|linear-gradient\(|radial-gradient\(/);
const html = read("index.html");
assert.ok(html.indexOf('/crm-reports.css?v=') > html.indexOf('/crm-team.css?v='));
const config = JSON.parse(read("vercel.json"));
assert.ok(config.builds.some(item => item.src === "crm-reports.css" && item.use === "@vercel/static"));
assert.ok(config.routes.some(item => item.src === "/crm-reports.css" && item.dest === "/crm-reports.css"));
assert.ok(read("server.js").includes('["/crm-reports.css", "crm-reports.css"]'));
assert.ok(read("sw.js").includes('"/crm-reports.css"'));
assert.match(read("client.js"), /<h3>\$\{pageTitleMarkup\(title\)\}<\/h3>/);
assert.match(read("client.js"), /weeklyCompletionSnapshot\(wrapper\)/);
console.log("PASS shared report surfaces, field feedback, readable dates and responsive contracts");
